#!/usr/bin/env python3
"""
Lab 01: Hello World Node - Basic Q&A Agent
Extended in Lab 02: Visualizing Your First Graph
"""

from typing import TypedDict
from langgraph.graph import StateGraph, END

# Define the Graph State Schema (from Lab 01)
class GraphState(TypedDict):
    """
    Represents the state of our graph for a basic Q&A agent.
    question: The input question string.
    answer: The final answer string generated by the node.
    """
    question: str
    answer: str

# Initial state (from Lab 01)
initial_state = {
    "question": "What is the primary use case for AWS S3?",
    "answer": ""
}

print("State Schema defined.")

# Define the basic_answer_node function (from Lab 01)
def basic_answer_node(state: GraphState) -> GraphState:
    """
    This node reads the input question and provides a hardcoded,
    context-specific answer, simulating an LLM response.
    """
    print("\n--- Executing Node: BASIC ANSWER NODE ---")

    # Extract the question from the state
    question = state.get("question", "No question found.")
    print(f"Question Received: {question}")

    # Define a simple, hardcoded answer related to the context
    simulated_answer = (
        "The primary use case for AWS S3 is object storage for things like "
        "static websites, backups, and data lakes."
    )

    # Return the state update dictionary, updating the 'answer' key
    return {"answer": simulated_answer}

print("Node function defined.")

# Build the Graph (from Lab 01)
workflow = StateGraph(GraphState)

# Add the Node (from Lab 01)
workflow.add_node("answer_node", basic_answer_node)

# Define the Entry and Exit (from Lab 01)
workflow.set_entry_point("answer_node")
workflow.add_edge("answer_node", END)

# ======================================================================
# LAB 02 STARTS HERE — Visualization TODOs
# ======================================================================

# Visualization helper (Lab 02)
def visualize_graph(app):
    """
    Generate and save a PNG visualization of the graph.
    """
    # TODO 1: Generate PNG bytes for the graph visualization
    png_data = app.get_graph().draw_mermaid_png()  # Replace ___ with: app.get_graph().draw_mermaid_png()

    # TODO 2: Save the PNG bytes to the file 'graph.png'
    with open("graph.png", "wb") as f:
        f.write(png_data)  # Replace ___ with: png_data  # Replace ___ with: png_data

# Compile the graph
app = workflow.compile()

print("\n--- Generating Graph Visualization ---")
# TODO 3: Call the visualize_graph helper before running the graph
visualize_graph(app)  # Replace ___ with: app  # Replace ___ with: app

print("\n--- Running the Compiled Graph ---")

# Run the graph with the initial state
final_state = app.invoke(initial_state)

# Review the Final State
print("\n--- FINAL GRAPH STATE ---")
print(f"Input Question: {final_state['question']}")
print(f"Final Answer: {final_state['answer']}")

#!/usr/bin/env python3
"""
Lab 03: Search or Answer Agent
Build an agent that decides whether to answer directly or search the web first.
"""

from typing import TypedDict
from langgraph.graph import StateGraph, END
from langchain_openai import ChatOpenAI
from tavily import TavilyClient

# 0. Tavily client (uses TAVILY_API_KEY from environment)
try:
    tavily_client = TavilyClient()  # will read TAVILY_API_KEY if set
except Exception as e:
    print(f"Warning: TavilyClient could not be initialized: {e}")
    tavily_client = None


# 1. Define the Graph State Schema
class GraphState(TypedDict):
    """
    Represents the state of our search-or-answer agent.

    Fields:
        question: The user's input question.
        answer: The final answer generated by the agent.
        needs_search: Boolean flag indicating if a web search is required.
        search_results: Raw text of the search results (if any).
    """
    question: str
    answer: str
    needs_search: bool
    search_results: str


# TODO 1: Create an initial state for execution
initial_state: GraphState = {
    "question": "What is the weather today?",       # Replace ___ with: "What is the weather today?"
    "answer": "",
    "needs_search": False,     # Replace ___ with: False
    "search_results": "", # Replace ___ with: ""
}

print("State schema defined and initial state created.")


# 2. Router Node: Determine if search is needed
def router_node(state: GraphState) -> GraphState:
    """
    Determines if the question requires web search.
    Simple questions (e.g., definitions) can be answered directly.
    Questions about current events, specific data, or recent information need search.
    """
    print("\n--- Executing Node: ROUTER ---")
    question = state.get("question", "")

    # Simple heuristic: questions with these keywords need web search
    search_keywords = ["today", "current", "latest", "recent", "now", "what is the weather"]

    # TODO 2: Decide whether this question needs web search using search_keywords
    needs_search = any(keyword in question.lower() for keyword in search_keywords)  # Replace ___ with: any(keyword in question.lower() for keyword in search_keywords)

    print(f"Question: {question}")
    print(f"Needs Search: {needs_search}")

    # Only needs_search is updated here
    return {"needs_search": needs_search}


# 3. Search Node (Tavily)
def search_node(state: GraphState) -> GraphState:
    """
    Performs web search with Tavily and stores results.
    """
    print("\n--- Executing Node: SEARCH ---")
    question = state.get("question", "")

    if tavily_client is None:
        print("Tavily client not available. Skipping search.")
        return {"search_results": "Search unavailable"}

    try:
        # Basic Tavily search; returns a dict with 'answer' and 'results'
        response = tavily_client.search(query=question)
        # Prefer the concise 'answer' field if available, otherwise join result snippets
        search_answer = response.get("answer")
        if search_answer:
            search_results = search_answer
        else:
            parts = []
            for r in response.get("results", []):
                title = r.get("title", "")
                content = r.get("content", "")
                parts.append(f"{title}: {content}")
            search_results = "\n\n".join(parts) if parts else str(response)

        print(f"Search Results (truncated): {search_results[:200]}...")
        return {"search_results": search_results}
    except Exception as e:
        print(f"Search failed: {e}")
        return {"search_results": "Search unavailable"}


# 4. Answer Node
def answer_node(state: GraphState) -> GraphState:
    """
    Generates the final answer using LLM.
    Uses search results if available, otherwise answers directly.
    """
    print("\n--- Executing Node: ANSWER ---")
    question = state.get("question", "")
    search_results = state.get("search_results", "")
    needs_search = state.get("needs_search", False)

    # TODO 3: Initialize ChatOpenAI with an allowed model
    llm = ChatOpenAI(model="openai/gpt-5-nano", temperature=0)  # Replace ___ with: "openai/gpt-5-nano"

    if needs_search and search_results:
        prompt = f"""Based on the following search results, answer the question.

Question: {question}

Search Results: {search_results}

Answer:"""
    else:
        prompt = f"""Answer the following question directly.

Question: {question}

Answer:"""

    response = llm.invoke(prompt)
    answer = response.content

    print(f"Generated Answer: {answer}")
    return {"answer": answer}


# 5. Conditional Edge Function
def should_search(state: GraphState) -> str:
    """Returns the next node based on whether search is needed."""
    if state.get("needs_search", False):
        return "search"
    return "answer"


# 6. Build the Graph
workflow = StateGraph(GraphState)

# Add nodes
workflow.add_node("router", router_node)
workflow.add_node("search", search_node)
workflow.add_node("answer", answer_node)

# Set entry point
workflow.set_entry_point("router")

# TODO 4: Wire conditional edges from 'router' based on should_search
workflow.add_conditional_edges(
    "router",
    should_search,
    {
        "search": "search",  # Replace ___ with: "search"
        "answer": "answer",  # Replace ___ with: "answer"
    },
)

# Add edge from search to answer
# TODO 5: Ensure that after 'search' finishes, execution goes to 'answer'
workflow.add_edge("search", "answer")  # Replace ___ with: "answer"

# Add edge from answer to END
workflow.add_edge("answer", END)

# Compile the app
app = workflow.compile()

# 7. Run the Graph once with the initial state
print("\n--- Running Search or Answer Agent ---")
final_state = app.invoke(initial_state)

print(f"Question: {final_state['question']}")
print(f"Needs Search: {final_state['needs_search']}")
print(f"Answer: {final_state['answer']}")